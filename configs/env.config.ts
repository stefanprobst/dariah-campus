import { addTrailingSlash, removeTrailingSlash } from "@acdh-oeaw/lib";
import * as v from "valibot";

import { define } from "#/lib/env/index.ts";

const validate = define({
	buildArgsPrefix: "NEXT_PUBLIC_",
	buildArgs: v.object({
		NEXT_PUBLIC_APP_BASE_URL: v.optional(
			v.pipe(v.string(), v.url(), v.transform(removeTrailingSlash)),
			`https://${String(process.env.NEXT_PUBLIC_VERCEL_URL)}`,
		),
		NEXT_PUBLIC_APP_PRODUCTION_BASE_URL: v.optional(
			v.pipe(v.string(), v.url(), v.transform(removeTrailingSlash)),
			`https://${String(process.env.NEXT_PUBLIC_VERCEL_PROJECT_PRODUCTION_URL)}`,
		),
		NEXT_PUBLIC_BOTS: v.optional(v.picklist(["disabled", "enabled"]), "disabled"),
		NEXT_PUBLIC_GOOGLE_SITE_VERIFICATION: v.optional(v.pipe(v.string(), v.nonEmpty())),
		NEXT_PUBLIC_MATOMO_BASE_URL: v.optional(v.pipe(v.string(), v.url(), v.transform(addTrailingSlash))),
		NEXT_PUBLIC_MATOMO_ID: v.optional(v.pipe(v.string(), v.toNumber(), v.integer(), v.minValue(1))),
		NEXT_PUBLIC_TYPESENSE_COLLECTION: v.pipe(v.string(), v.nonEmpty()),
		NEXT_PUBLIC_TYPESENSE_HOST: v.pipe(v.string(), v.nonEmpty()),
		NEXT_PUBLIC_TYPESENSE_PORT: v.pipe(v.string(), v.toNumber(), v.integer(), v.minValue(1)),
		NEXT_PUBLIC_TYPESENSE_PROTOCOL: v.optional(v.picklist(["http", "https"]), "https"),
		/**
		 * Optional, because we need to be able to create a collection, before we create a search-only api key for that
		 * collection.
		 */
		NEXT_PUBLIC_TYPESENSE_SEARCH_API_KEY: v.optional(v.pipe(v.string(), v.nonEmpty())),
	}),
	envVars: v.object({
		BUILD_MODE: v.optional(v.picklist(["export", "standalone"])),
		CI: v.optional(v.pipe(v.unknown(), v.toBoolean())),
		CMS_BASE_URL: v.optional(v.pipe(v.string(), v.url(), v.transform(removeTrailingSlash))),
		CMS_CONFIG_REPO: v.optional(v.pipe(v.string(), v.regex(/^[^/]+\/[^/]+$/))),
		CMS_CONTENT_BRANCH: v.optional(v.pipe(v.string(), v.nonEmpty()), "main"),
		CMS_CONTENT_REPO: v.optional(v.pipe(v.string(), v.regex(/^[^/]+\/[^/]+$/))),
		CMS_GITHUB_APP_ID: v.optional(v.pipe(v.string(), v.nonEmpty())),
		CMS_GITHUB_APP_INSTALLATION_ID: v.optional(v.pipe(v.string(), v.nonEmpty())),
		CMS_GITHUB_APP_PRIVATE_KEY: v.optional(v.pipe(v.string(), v.nonEmpty())),
		CMS_GITHUB_CLIENT_ID: v.optional(v.pipe(v.string(), v.nonEmpty())),
		CMS_GITHUB_CLIENT_SECRET: v.optional(v.pipe(v.string(), v.nonEmpty())),
		CMS_IMGPROXY_KEY: v.optional(v.pipe(v.string(), v.hexadecimal())),
		CMS_IMGPROXY_SALT: v.optional(v.pipe(v.string(), v.hexadecimal())),
		CMS_IMGPROXY_URL: v.optional(v.pipe(v.string(), v.url(), v.transform(removeTrailingSlash))),
		CMS_ROOT: v.optional(v.pipe(v.string(), v.nonEmpty()), ".cms-migration"),
		CMS_S3_ACCESS_KEY_ID: v.optional(v.pipe(v.string(), v.nonEmpty())),
		CMS_S3_BUCKET: v.optional(v.pipe(v.string(), v.nonEmpty())),
		CMS_S3_ENDPOINT: v.optional(v.pipe(v.string(), v.url(), v.transform(removeTrailingSlash))),
		CMS_S3_PUBLIC_URL: v.optional(v.pipe(v.string(), v.url(), v.transform(removeTrailingSlash))),
		CMS_S3_SECRET_ACCESS_KEY: v.optional(v.pipe(v.string(), v.nonEmpty())),
		CMS_SECRET: v.optional(v.pipe(v.string(), v.minLength(32))),
		HANDLE_CERT: v.optional(v.pipe(v.string(), v.nonEmpty())),
		HANDLE_KEY: v.optional(v.pipe(v.string(), v.nonEmpty())),
		HANDLE_PREFIX: v.optional(v.pipe(v.string(), v.nonEmpty())),
		HANDLE_PROVIDER: v.optional(v.pipe(v.string(), v.url())),
		HANDLE_RESOLVER: v.optional(v.pipe(v.string(), v.url())),
		NEXT_RUNTIME: v.optional(v.picklist(["edge", "nodejs"])),
		PORT: v.optional(v.pipe(v.string(), v.toNumber(), v.integer(), v.minValue(1))),
		TYPESENSE_ADMIN_API_KEY: v.pipe(v.string(), v.nonEmpty()),
		VERCEL_ENV: v.optional(v.pipe(v.string(), v.nonEmpty())),
		VERCEL_GIT_COMMIT_REF: v.optional(v.pipe(v.string(), v.nonEmpty())),
	}),
});

export const env = validate({
	environment: {
		BUILD_MODE: process.env.BUILD_MODE,
		CI: process.env.CI,
		CMS_BASE_URL: process.env.CMS_BASE_URL,
		CMS_CONFIG_REPO: process.env.CMS_CONFIG_REPO,
		CMS_CONTENT_BRANCH: process.env.CMS_CONTENT_BRANCH,
		CMS_CONTENT_REPO: process.env.CMS_CONTENT_REPO,
		CMS_GITHUB_APP_ID: process.env.CMS_GITHUB_APP_ID,
		CMS_GITHUB_APP_INSTALLATION_ID: process.env.CMS_GITHUB_APP_INSTALLATION_ID,
		CMS_GITHUB_APP_PRIVATE_KEY: process.env.CMS_GITHUB_APP_PRIVATE_KEY,
		CMS_GITHUB_CLIENT_ID: process.env.CMS_GITHUB_CLIENT_ID,
		CMS_GITHUB_CLIENT_SECRET: process.env.CMS_GITHUB_CLIENT_SECRET,
		CMS_IMGPROXY_KEY: process.env.CMS_IMGPROXY_KEY,
		CMS_IMGPROXY_SALT: process.env.CMS_IMGPROXY_SALT,
		CMS_IMGPROXY_URL: process.env.CMS_IMGPROXY_URL,
		CMS_ROOT: process.env.CMS_ROOT,
		CMS_S3_ACCESS_KEY_ID: process.env.CMS_S3_ACCESS_KEY_ID,
		CMS_S3_BUCKET: process.env.CMS_S3_BUCKET,
		CMS_S3_ENDPOINT: process.env.CMS_S3_ENDPOINT,
		CMS_S3_PUBLIC_URL: process.env.CMS_S3_PUBLIC_URL,
		CMS_S3_SECRET_ACCESS_KEY: process.env.CMS_S3_SECRET_ACCESS_KEY,
		CMS_SECRET: process.env.CMS_SECRET,
		HANDLE_CERT: process.env.HANDLE_CERT,
		HANDLE_KEY: process.env.HANDLE_KEY,
		HANDLE_PREFIX: process.env.HANDLE_PREFIX,
		HANDLE_PROVIDER: process.env.HANDLE_PROVIDER,
		HANDLE_RESOLVER: process.env.HANDLE_RESOLVER,
		NEXT_PUBLIC_APP_BASE_URL: process.env.NEXT_PUBLIC_APP_BASE_URL,
		NEXT_PUBLIC_APP_PRODUCTION_BASE_URL: process.env.NEXT_PUBLIC_APP_PRODUCTION_BASE_URL,
		NEXT_PUBLIC_BOTS: process.env.NEXT_PUBLIC_BOTS,
		NEXT_PUBLIC_GOOGLE_SITE_VERIFICATION: process.env.NEXT_PUBLIC_GOOGLE_SITE_VERIFICATION,
		NEXT_PUBLIC_MATOMO_BASE_URL: process.env.NEXT_PUBLIC_MATOMO_BASE_URL,
		NEXT_PUBLIC_MATOMO_ID: process.env.NEXT_PUBLIC_MATOMO_ID,
		NEXT_PUBLIC_TYPESENSE_COLLECTION: process.env.NEXT_PUBLIC_TYPESENSE_COLLECTION,
		NEXT_PUBLIC_TYPESENSE_HOST: process.env.NEXT_PUBLIC_TYPESENSE_HOST,
		NEXT_PUBLIC_TYPESENSE_PORT: process.env.NEXT_PUBLIC_TYPESENSE_PORT,
		NEXT_PUBLIC_TYPESENSE_PROTOCOL: process.env.NEXT_PUBLIC_TYPESENSE_PROTOCOL,
		NEXT_PUBLIC_TYPESENSE_SEARCH_API_KEY: process.env.NEXT_PUBLIC_TYPESENSE_SEARCH_API_KEY,
		NEXT_RUNTIME: process.env.NEXT_RUNTIME,
		NODE_ENV: process.env.NODE_ENV,
		PORT: process.env.PORT,
		TYPESENSE_ADMIN_API_KEY: process.env.TYPESENSE_ADMIN_API_KEY,
		VERCEL_ENV: process.env.VERCEL_ENV,
		VERCEL_GIT_COMMIT_REF: process.env.VERCEL_GIT_COMMIT_REF,
	},
}).unwrap();
